CREATE TABLE listings
(
    id          Number(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_Id  VARCHAR2(50)    NOT NULL,
    source      VARCHAR2(50)    NOT NULL,
    address     VARCHAR2(200)   NOT NULL,
    city        VARCHAR2(100)   NOT NULL,
    state       VARCHAR2(2)     NOT NULL,
    zip         VARCHAR2(10)    NOT NULL,
    price       NUMBER(19,2)    NOT NULL,
    bedrooms    NUMBER(3)       NOT NULL,
    bathrooms   NUMBER(4,1)     NOT NULL,
    sqft        NUMBER(7)       NOT NULL,
    latitude    NUMBER(9, 6),
    longitude   NUMBER(9, 6),
    listed_date DATE NOT NULL,
    status      VARCHAR2(20)    NOT NULL,
    description VARCHAR2(2000),
    CONSTRAINT uq_listings_source_listing UNIQUE (source, listing_id)
);

CREATE INDEX ix_listings_price ON listings (price);
CREATE INDEX ix_listings_city ON listings (city);
CREATE INDEX ix_listings_listed_date ON listings (listed_date);